#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"

# Per-build randomised identifiers. Every artifact that touches disk, logcat or
# a GitHub release carries a different name.
rand() { tr -dc 'a-z0-9' </dev/urandom | head -c "$1" ; }
randl() { tr -dc 'a-z' </dev/urandom | head -c "$1" ; }

BUILD_TAG=${BUILD_TAG:-$(randl 3)}
BUILD_SLUG=${BUILD_SLUG:-$(rand 8)}
BUILD_PKG=${BUILD_PKG:-"com.android.oemsupport.a$(rand 6)"}
BUILD_CLASS_BRIDGE_SHORT=$(randl 1)$(rand 4)
BUILD_CLASS_ENTRY_SHORT=$(randl 1)$(rand 4)
BUILD_LIB_PREFIX=${BUILD_LIB_PREFIX:-"libart$(rand 3)_"}
BUILD_PREFS=${BUILD_PREFS:-"cfg_$(rand 6)"}
BUILD_LIBNAME=${BUILD_LIBNAME:-"lib$(rand 6)"}
BUILD_LOADER=${BUILD_LOADER:-".ld$(rand 4)"}
BUILD_SCRIPT=${BUILD_SCRIPT:-"update_$(rand 5).sh"}

CLASS_BRIDGE_FQN="${BUILD_PKG}.${BUILD_CLASS_BRIDGE_SHORT}"
CLASS_ENTRY_FQN="${BUILD_PKG}.${BUILD_CLASS_ENTRY_SHORT}"
TARGET_PKG=${TARGET_PKG:-"com.catsbit.oxidesurvivalisland"}

echo "build id: tag=$BUILD_TAG slug=$BUILD_SLUG pkg=$BUILD_PKG libname=$BUILD_LIBNAME loader=$BUILD_LOADER script=$BUILD_SCRIPT"

# Write brand.h with the chosen values so the native side matches.
cat > native/brand.h <<EOF
#pragma once
// AUTOGENERATED per-build. Do not commit real values.
#define BRAND_TAG "${BUILD_TAG}"
#define BRAND_PKG "${BUILD_PKG}"
#define BRAND_CLASS_BRIDGE "${CLASS_BRIDGE_FQN}"
#define BRAND_CLASS_ENTRY "${CLASS_ENTRY_FQN}"
#define BRAND_LIB_PREFIX "${BUILD_LIB_PREFIX}"
#define BRAND_PREFS_NAME "${BUILD_PREFS}"
#define BRAND_SOUND_NAME "${BUILD_LIBNAME}.ogg"
EOF

# Rewrite Java sources into a staging tree under the randomised package.
staging=build/java-staging
rm -rf "$staging" && mkdir -p "$staging"
pkg_path=${BUILD_PKG//.//}
mkdir -p "$staging/$pkg_path"
for src in java/com/cloudcrack/oxide/*.java; do
    base=$(basename "$src" .java)
    case "$base" in
        InternalBridge) dst="$staging/$pkg_path/${BUILD_CLASS_BRIDGE_SHORT}.java" ;;
        InternalEntry)  dst="$staging/$pkg_path/${BUILD_CLASS_ENTRY_SHORT}.java"  ;;
        *)              dst="$staging/$pkg_path/${base}.java"                      ;;
    esac
    sed \
        -e "s|package com.cloudcrack.oxide;|package ${BUILD_PKG};|" \
        -e "s|\\bInternalBridge\\b|${BUILD_CLASS_BRIDGE_SHORT}|g" \
        -e "s|\\bInternalEntry\\b|${BUILD_CLASS_ENTRY_SHORT}|g" \
        -e "s|\"Oxide_Internal\"|\"${BUILD_TAG}\"|g" \
        -e "s|\"oxide_internal_12034\"|\"${BUILD_PREFS}\"|g" \
        -e "s|Oxide_Internal_12034.json|${BUILD_PREFS}.json|g" \
        "$src" > "$dst"
done

JAVA_SOURCE_DIR="$staging" bash build.sh

sdk=${ANDROID_SDK_ROOT:-${ANDROID_HOME:-/workspace/android-sdk}}
ndk=${ANDROID_NDK_HOME:-"$sdk/ndk/27.2.12479018"}
llvm="$ndk/toolchains/llvm/prebuilt/linux-x86_64/bin"

# Rename the compiled outputs to randomised names before packing and striping.
mv dist/oxide-loader "dist/${BUILD_LOADER}"
mv dist/oxide12034.so "dist/${BUILD_LIBNAME}.so"
mv dist/oxide12034.dex "dist/${BUILD_LIBNAME}.dex"
if [ -f assets/hitsound.ogg ]; then
    cp assets/hitsound.ogg "dist/${BUILD_LIBNAME}.ogg"
elif [ -f dist/rust_headshot.ogg ]; then
    cp dist/rust_headshot.ogg "dist/${BUILD_LIBNAME}.ogg"
else
    echo "missing hitsound source" >&2; exit 1
fi

"$llvm/llvm-strip" --strip-all --remove-section=.comment --remove-section=.note \
    "dist/${BUILD_LOADER}" "dist/${BUILD_LIBNAME}.so"

tar -czf dist/payload.tar.gz -C dist \
    "${BUILD_LOADER}" "${BUILD_LIBNAME}.so" "${BUILD_LIBNAME}.dex" "${BUILD_LIBNAME}.ogg"

out="dist/${BUILD_SCRIPT}"
sed \
    -e "s|@PKG@|${TARGET_PKG}|g" \
    -e "s|@SLUG@|${BUILD_SLUG}|g" \
    -e "s|@LOADER@|${BUILD_LOADER}|g" \
    -e "s|@LIBNAME@|${BUILD_LIBNAME}|g" \
    launcher.sh.in > "$out"
base64 dist/payload.tar.gz >> "$out"
chmod 755 "$out"
sh "$out" --verify
ls -lh "$out"
