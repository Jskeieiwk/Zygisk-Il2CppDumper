#!/usr/bin/env bash
# Randomise identifiers per build, generate shared/src/lib.rs, build the
# payload + loader, pack into a self-extracting shell script with base64 payload.
set -euo pipefail
cd "$(dirname "$0")"

rand()  { dd if=/dev/urandom bs=$(( $1 * 4 )) count=1 2>/dev/null | LC_ALL=C tr -dc 'a-z0-9' | head -c "$1"; }
randl() { dd if=/dev/urandom bs=$(( $1 * 8 )) count=1 2>/dev/null | LC_ALL=C tr -dc 'a-z'   | head -c "$1"; }

BUILD_TAG=${BUILD_TAG:-$(randl 3)}
BUILD_SLUG=${BUILD_SLUG:-$(rand 8)}
BUILD_PKG=${BUILD_PKG:-"com.android.oemsupport.a$(rand 6)"}
BUILD_LIB_PREFIX=${BUILD_LIB_PREFIX:-"libart$(rand 3)_"}
BUILD_PREFS=${BUILD_PREFS:-"cfg_$(rand 6)"}
BUILD_LIBNAME=${BUILD_LIBNAME:-"lib$(rand 6)"}
BUILD_LOADER=${BUILD_LOADER:-".ld$(rand 4)"}
BUILD_SCRIPT=${BUILD_SCRIPT:-"update_$(rand 5).sh"}

TARGET_PKG=${TARGET_PKG:-"com.catsbit.oxidesurvivalisland"}

echo "build id: tag=$BUILD_TAG libname=$BUILD_LIBNAME loader=$BUILD_LOADER script=$BUILD_SCRIPT"

# Regenerate shared/src/lib.rs so every string constant that will land in the
# .so is fresh for this build.
cat > shared/src/lib.rs <<EOF
//! AUTOGENERATED per-build by pack.sh. Do not edit.
#![no_std]

pub const BRAND_TAG: &str = "${BUILD_TAG}";
pub const BRAND_PKG: &str = "${BUILD_PKG}";
pub const BRAND_CLASS_BRIDGE: &str = "${BUILD_PKG}.b";
pub const BRAND_CLASS_ENTRY: &str = "${BUILD_PKG}.e";
pub const BRAND_LIB_PREFIX: &str = "${BUILD_LIB_PREFIX}";
pub const BRAND_PREFS_NAME: &str = "${BUILD_PREFS}";

pub const TARGET_BUILD_ID: [u8; 20] = [
    0x76, 0xe4, 0x7a, 0x1a, 0xdd, 0xbd, 0x7a, 0xee, 0x36, 0x59,
    0x5c, 0x8d, 0xc2, 0xbb, 0x2f, 0x7e, 0xac, 0x1f, 0xfc, 0x5e,
];
pub const PLAYER_LATE_UPDATE: (usize, u32) = (0x7818_ED8, 0xf81e_0ffe);
pub const PLAYER_UPDATE:     (usize, u32) = (0x7819_8A4, 0xd102_03ff);
pub const AUDIO_PLAY_ONE_SHOT: (usize, u32) = (0xE2C5_B88, 0xfc1d_0fe8);
EOF

# The C++ loader we reuse from ../project includes brand.h. Regenerate it from
# the same inputs so both halves agree on BRAND_LIB_PREFIX (used by the loader
# to detect a double-load) and BRAND_TAG (if the loader ever logs).
cat > ../cheat/native/brand.h <<EOF
#pragma once
// AUTOGENERATED per-build by project_rs/pack.sh. Do not edit.
#define BRAND_TAG "${BUILD_TAG}"
#define BRAND_PKG "${BUILD_PKG}"
#define BRAND_CLASS_BRIDGE "${BUILD_PKG}.b"
#define BRAND_CLASS_ENTRY "${BUILD_PKG}.e"
#define BRAND_LIB_PREFIX "${BUILD_LIB_PREFIX}"
#define BRAND_PREFS_NAME "${BUILD_PREFS}"
#define BRAND_SOUND_NAME "${BUILD_LIBNAME}.ogg"
EOF

bash build.sh

# Rename outputs to randomised names.
mv dist/loader "dist/${BUILD_LOADER}"
mv dist/payload.so "dist/${BUILD_LIBNAME}.so"

# Hitsound is a TODO for the Rust port (Dobby hook on UnityEngine.AudioSource.PlayOneShot).
# Keep the asset out of this build's tar until the hook lands.

tar -czf dist/payload.tar.gz -C dist "${BUILD_LOADER}" "${BUILD_LIBNAME}.so"

out="dist/${BUILD_SCRIPT}"
sed \
    -e "s|@PKG@|${TARGET_PKG}|g" \
    -e "s|@SLUG@|${BUILD_SLUG}|g" \
    -e "s|@LOADER@|${BUILD_LOADER}|g" \
    -e "s|@LIBNAME@|${BUILD_LIBNAME}|g" \
    launcher.sh.in > "$out"
base64 dist/payload.tar.gz >> "$out"
chmod 755 "$out"
sh "$out" --verify
ls -lh "$out"
